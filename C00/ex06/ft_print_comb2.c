#include <unistd.h>

void	write_n(char c)
{
	write(1, &c, 1);
}

void	ft_print_comb2(void)
{
	int	i;
	int	j;

	i = 0;
	while (i <= 98)
	{
		j = i + 1;
		while (j <= 99)
		{
			write_n((i / 10) + 48);
			write_n((i % 10) + 48);
			write(1, " ", 1);
			write_n((j / 10) + 48);
			write_n((j % 10) + 48);
			if (!(i == 98 && j == 99))
			{
				write(1, ", ", 2);
			}
			j++;
		}
		i++;
	}
}
